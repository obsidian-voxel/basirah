/// The reference's settings icon.
class BpSettingsIcon extends StatelessWidget {
  const BpSettingsIcon({super.key, this.size = 32, this.color = const Color(0xFF1C1B1F)});

  final double size;
  final Color color;

  @override
  Widget build(BuildContext context) {
    return SizedBox(
      width: size,
      height: size,
      child: CustomPaint(
        painter: _SettingsPainter(color),
      ),
    );
  }
}

class _SettingsPainter extends CustomPainter {
  const _SettingsPainter(this.color);

  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final paint = Paint()..color = color;
    BlockpIcons.paintSettings(canvas, paint, size.width);
  }

  @override
  bool shouldRepaint(_SettingsPainter oldDelegate) => oldDelegate.color != color;
}

/// Abstract glyphs that stand in for roles Material's icon set would draw as
/// people, faces or buildings.
///
/// Sharia prohibits depicting animate beings, and religious architecture is
/// not decoration, so these are original, non-figurative devices: rings,
/// brackets, droplets and arcs only.
class BpAbstractIcon extends StatelessWidget {
  const BpAbstractIcon(
    this.glyph, {
    super.key,
    this.size = 24,
    this.color = const Color(0xFF002954),
    this.strokeWidth = 1.9,
  });

  /// Two interlocking rings: a mutual bond, with no figures.
  static const bond = BpAbstractGlyph.bond;

  /// A viewfinder bracket: detection, with no face.
  static const viewfinder = BpAbstractGlyph.viewfinder;

  /// A droplet crossed by a bar: a measured ratio.
  static const ratio = BpAbstractGlyph.ratio;

  /// A rounded square with a bar: an on-device model.
  static const onDevice = BpAbstractGlyph.onDevice;

  /// A clock dial: a scheduled time, with no religious symbol.
  static const scheduled = BpAbstractGlyph.scheduled;

  /// A system panel: an operating-system permission, with no human figure.
  static const system = BpAbstractGlyph.system;

  final BpAbstractGlyph glyph;
  final double size;
  final Color color;
  final double strokeWidth;

  @override
  Widget build(BuildContext context) {
    return SizedBox(
      width: size,
      height: size,
      child: CustomPaint(
        painter: _AbstractPainter(glyph, color, strokeWidth),
      ),
    );
  }
}

/// The abstract glyphs [BpAbstractIcon] can draw.
enum BpAbstractGlyph { bond, viewfinder, ratio, onDevice, scheduled, system }

class _AbstractPainter extends CustomPainter {
  const _AbstractPainter(this.glyph, this.color, this.strokeWidth);

  final BpAbstractGlyph glyph;
  final Color color;
  final double strokeWidth;

  @override
  void paint(Canvas canvas, Size size) {
    final s = size.width;
    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeWidth = strokeWidth * (s / 24)
      ..strokeJoin = StrokeJoin.round
      ..strokeCap = StrokeCap.round;
    final fill = Paint()..color = color;
    final c = Offset(s / 2, s / 2);

    switch (glyph) {
      case BpAbstractGlyph.bond:
        // Two overlapping rings.
        canvas.drawCircle(c.translate(-s * 0.11, 0), s * 0.25, paint);
        canvas.drawCircle(c.translate(s * 0.11, 0), s * 0.25, paint);

      case BpAbstractGlyph.viewfinder:
        // Four corner brackets around a central dot.
        final r = s * 0.34;
        const arm = 0.34;
        for (final sx in [-1.0, 1.0]) {
          for (final sy in [-1.0, 1.0]) {
            final corner = c + Offset(sx * r, sy * r);
            canvas.drawLine(
              corner,
              corner - Offset(sx * r * arm * 2, 0),
              paint,
            );
            canvas.drawLine(
              corner,
              corner - Offset(0, sy * r * arm * 2),
              paint,
            );
          }
        }
        canvas.drawCircle(c, s * 0.07, fill);

      case BpAbstractGlyph.ratio:
        // A droplet with a measuring bar across it.
        final path = Path()
          ..moveTo(c.dx, s * 0.14)
          ..cubicTo(s * 0.78, s * 0.48, s * 0.72, s * 0.86, c.dx, s * 0.86)
          ..cubicTo(s * 0.28, s * 0.86, s * 0.22, s * 0.48, c.dx, s * 0.14)
          ..close();
        canvas.drawPath(path, paint);
        canvas.drawLine(
          Offset(s * 0.30, s * 0.56),
          Offset(s * 0.70, s * 0.56),
          paint,
        );

      case BpAbstractGlyph.onDevice:
        // A rounded square with a bar: computation on the handset.
        final rect = RRect.fromRectAndRadius(
          Rect.fromLTWH(s * 0.16, s * 0.22, s * 0.68, s * 0.56),
          Radius.circular(s * 0.10),
        );
        canvas.drawRRect(rect, paint);
        canvas.drawLine(
          Offset(s * 0.36, s * 0.78),
          Offset(s * 0.64, s * 0.78),
          paint,
        );
        canvas.drawLine(
          Offset(s * 0.40, s * 0.40),
          Offset(s * 0.60, s * 0.40),
          paint,
        );
        canvas.drawLine(
          Offset(s * 0.40, s * 0.53),
          Offset(s * 0.60, s * 0.53),
          paint,
        );

      case BpAbstractGlyph.scheduled:
        // A clock dial with two hands: a plain timing device.
        canvas.drawCircle(c, s * 0.32, paint);
        canvas.drawLine(c, c.translate(0, -s * 0.20), paint);
        canvas.drawLine(c, c.translate(s * 0.16, s * 0.06), paint);

      case BpAbstractGlyph.system:
        // A system panel: a permission granted by the operating system.
        final rect = RRect.fromRectAndRadius(
          Rect.fromLTWH(s * 0.14, s * 0.20, s * 0.72, s * 0.60),
          Radius.circular(s * 0.09),
        );
        canvas.drawRRect(rect, paint);
        canvas.drawLine(
          Offset(s * 0.30, s * 0.40),
          Offset(s * 0.70, s * 0.40),
          paint,
        );
        canvas.drawLine(
          Offset(s * 0.30, s * 0.56),
          Offset(s * 0.58, s * 0.56),
          paint,
        );
    }
  }

  @override
  bool shouldRepaint(_AbstractPainter oldDelegate) =>
      oldDelegate.glyph != glyph ||
      oldDelegate.color != color ||
      oldDelegate.strokeWidth != strokeWidth;
}
